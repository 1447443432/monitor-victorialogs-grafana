#!/bin/bash
set -e

###############################################################################
# HAP Monitor Build Script
#
# 用法:
#   ./build.sh
#   ./build.sh -a amd64
#   ./build.sh -a arm64
#   ./build.sh -c
#   ./build.sh -n
#   ./build.sh -cn
#   ./build.sh -a arm64 -cn
#
# 参数:
#   -a, --arch
#       指定架构：amd64 或 arm64
#       默认自动识别当前主机架构
#
#   -c, --clean
#       清理 dangling 镜像 + build cache
#
#   -n, --no-cache
#       docker build 不使用缓存
#
#   -h, --help
#       查看帮助
###############################################################################

REGISTRY="registry.cn-hangzhou.aliyuncs.com/hap-mdy"

IMAGE_BASE_NAME="hap-monitor-victorialogs-grafana"

IMAGE_TAG="1.0.0"

###############################################################################
# 自动识别主机架构
###############################################################################

HOST_ARCH="$(uname -m)"

case "${HOST_ARCH}" in
    x86_64|amd64)
        ARCH="amd64"
        ;;
    aarch64|arm64)
        ARCH="arm64"
        ;;
    *)
        echo ">>> 不支持的主机架构: ${HOST_ARCH}"
        exit 1
        ;;
esac

###############################################################################
# 默认参数
###############################################################################

CLEAN=false
NO_CACHE=false

###############################################################################
# Help
###############################################################################

usage() {
    grep '^#' "$0" | cut -c 3-
    exit 0
}

###############################################################################
# 参数解析
###############################################################################

while [[ $# -gt 0 ]]; do

    case "$1" in

        -a|--arch)

            ARCH="$2"

            shift
            ;;

        -c|--clean)

            CLEAN=true
            ;;

        -n|--no-cache)

            NO_CACHE=true
            ;;

        -cn|-nc)

            CLEAN=true
            NO_CACHE=true
            ;;

        -h|--help)

            usage
            ;;

        *)

            echo ">>> 未知参数: $1"

            echo

            usage
            ;;

    esac

    shift

done

###############################################################################
# 架构校验
###############################################################################

case "${ARCH}" in

    amd64|arm64)

        ;;

    *)

        echo ">>> 不支持的架构: ${ARCH}"

        echo ">>> 仅支持: amd64, arm64"

        exit 1

        ;;

esac

###############################################################################
# 镜像名
###############################################################################

IMAGE_NAME="${REGISTRY}/${IMAGE_BASE_NAME}-${ARCH}"

FULL_IMAGE="${IMAGE_NAME}:${IMAGE_TAG}"

###############################################################################
# 开始
###############################################################################

echo "============================================================================="

echo ">>> HAP Monitor 镜像构建开始"

echo ">>> 时间: $(date '+%Y-%m-%d %H:%M:%S')"

echo ">>> 主机架构: ${HOST_ARCH}"

echo ">>> 构建架构: ${ARCH}"

echo ">>> 镜像: ${FULL_IMAGE}"

echo "============================================================================="

###############################################################################
# Clean
###############################################################################

if [[ "${CLEAN}" == "true" ]]; then

    echo

    echo ">>> 清理 dangling 镜像..."

    docker image prune -f || true

    echo

    echo ">>> 清理 build cache..."

    docker builder prune -f || true

fi

###############################################################################
# Build
###############################################################################

echo

echo ">>> 开始 docker build..."

BUILD_CMD="docker build"

if [[ "${NO_CACHE}" == "true" ]]; then

    BUILD_CMD="${BUILD_CMD} --no-cache"

fi

BUILD_CMD="${BUILD_CMD} --build-arg TARGETARCH=${ARCH} -t ${FULL_IMAGE} ."

echo

echo ">>> 执行命令:"

echo "${BUILD_CMD}"

echo

eval "${BUILD_CMD}"

###############################################################################
# Result
###############################################################################

echo

echo ">>> 当前镜像:"

docker images | grep "${IMAGE_BASE_NAME}" || true

echo

echo "============================================================================="

echo ">>> HAP Monitor 镜像构建完成"

echo ">>> 时间: $(date '+%Y-%m-%d %H:%M:%S')"

echo ">>> 镜像: ${FULL_IMAGE}"

echo "============================================================================="

